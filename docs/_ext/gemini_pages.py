"""Generate the instrument, Gemini and core-method pages of the docs.

At the start of every build, this extension writes reStructuredText files
into ``api/`` (which is git-ignored, like the other generated files):

``api/core_methods.rst``
    The methods and properties of the core ``astrodata.AstroData`` class,
    linking to the astrodata documentation.

``api/gemini_descriptors.rst``
    The tags and the descriptors defined at the Gemini level.

``api/instruments/<instrument>.rst``
    For each instrument, the tags it can define and its descriptors, with
    their docstring and return type.  The descriptors inherited from the
    Gemini level are included.

Nothing is maintained by hand: a new descriptor or tag shows up the next time
the docs are built.
"""

"""
The first version of this extension was generated by Claude Code, guided by
Kathleen Labrie.  The two primary prompts were:
*  Here's what I'd like to see in the documentation. 1) A list of the core 
   astrodata methods (add, append, write, etc); 2) For each instrument, a 
   list of the tags that are defined; 3) For each instrument, a list of the 
   descriptor that are defined, with their docstring and their expected return 
   value type(s), this should include descriptors inherited from gemini; 
   4) then the list of descriptors defined at the gemini level.
*  I just want the names: DARK, FLAT, etc.  I don't really need docstrings or 
   link to the methods.  It is more informational than anything.  They are 
   not "actionable" but knowing which one can show up for an instrument can 
   be useful.
"""

import ast
import importlib
import inspect
import pkgutil
import re
import textwrap
from pathlib import Path

from sphinx.util import logging

logger = logging.getLogger(__name__)

_ADD_METHODS = ("append", "add", "extend", "update")


# -- Reading the tag names out of the source code ---------------------------


def _is_name(node, name):
    return isinstance(node, ast.Name) and node.id == name


def _dict_values(name, func, dyn):
    found = []
    for node in ast.walk(func):
        if (
            isinstance(node, ast.Assign)
            and any(_is_name(t, name) for t in node.targets)
            and isinstance(node.value, ast.Dict)
        ):
            for value in node.value.values:
                found.extend(_strings(value, func, (), dyn))
    return found


def _strings(node, func, seen=(), dyn=None):
    """Return the string literals that a node can evaluate to.

    Whatever cannot be read from the code (e.g. a value taken from a header)
    is appended to the ``dyn`` list, when one is given.
    """
    if isinstance(node, ast.Constant):
        return [node.value] if isinstance(node.value, str) else []
    if isinstance(node, (ast.List, ast.Set, ast.Tuple)):
        return [s for elt in node.elts for s in _strings(elt, func, seen, dyn)]
    if isinstance(node, ast.IfExp):
        return _strings(node.body, func, seen, dyn) + _strings(
            node.orelse, func, seen, dyn
        )
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id in ("set", "list", "tuple", "sorted")
        and node.args
    ):
        return _strings(node.args[0], func, seen, dyn)
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        return _dict_values(node.value.id, func, dyn)
    if isinstance(node, ast.Name):
        return _resolve_name(node.id, func, seen, dyn)
    if dyn is not None:
        dyn.append(node)
    return []


def _tagset_names(func):
    """Names of the local variables that hold a TagSet."""
    names = set()
    for node in ast.walk(func):
        if (
            isinstance(node, ast.Assign)
            and isinstance(node.value, ast.Call)
            and getattr(node.value.func, "id", "") == "TagSet"
        ):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return names


def _resolve_name(name, func, seen, dyn):
    """Return the strings assigned to, or added to, a local variable."""
    if name in seen:
        return []
    seen = (*seen, name)
    found = []
    local_dyn = []
    constrained = False
    for node in ast.walk(func):
        if isinstance(node, ast.Assign):
            if any(_is_name(t, name) for t in node.targets):
                found.extend(_strings(node.value, func, seen, local_dyn))
        elif isinstance(node, ast.AugAssign):
            if _is_name(node.target, name):
                found.extend(_strings(node.value, func, seen, local_dyn))
        elif isinstance(node, ast.Call) and isinstance(
            node.func, ast.Attribute
        ):
            if (
                _is_name(node.func.value, name)
                and node.func.attr in _ADD_METHODS
                and node.args
            ):
                found.extend(_strings(node.args[0], func, seen, local_dyn))
        elif isinstance(node, ast.For):
            target = node.target
            if _is_name(target, name):
                found.extend(_strings(node.iter, func, seen, local_dyn))
            elif isinstance(target, ast.Tuple):
                for index, elt in enumerate(target.elts):
                    if _is_name(elt, name) and isinstance(
                        node.iter, (ast.Tuple, ast.List)
                    ):
                        for pair in node.iter.elts:
                            if isinstance(pair, (ast.Tuple, ast.List)):
                                found.extend(
                                    _strings(
                                        pair.elts[index], func, seen, local_dyn
                                    )
                                )
        elif isinstance(node, ast.Compare):
            # A value tested against literals, e.g. "if camera in (...)",
            # can only be one of those literals.
            if _is_name(node.left, name):
                for op, comp in zip(node.ops, node.comparators):
                    if isinstance(op, (ast.In, ast.Eq)):
                        found.extend(_strings(comp, func, seen, local_dyn))
                        constrained = True
    if constrained:
        local_dyn = []
    elif not found and not local_dyn:
        local_dyn.append(name)
    if dyn is not None:
        dyn.extend(local_dyn)
    return found


def _tags_of_method(func, dyn=None):
    """Return the tag names that one ``@astro_data_tag`` method adds."""
    names = []
    tagset_vars = _tagset_names(func)
    for node in ast.walk(func):
        if not isinstance(node, ast.Call):
            continue
        # TagSet(["A", "B"], blocks=[...]) or TagSet(add=[...])
        if getattr(node.func, "id", "") == "TagSet":
            arg = node.args[0] if node.args else None
            for keyword in node.keywords:
                if keyword.arg == "add":
                    arg = keyword.value
            if arg is not None:
                names.extend(_strings(arg, func, (), dyn))
        # tags.add.add("A") where tags = TagSet()
        elif (
            isinstance(node.func, ast.Attribute)
            and node.func.attr in _ADD_METHODS
            and node.args
        ):
            owner = node.func.value
            if isinstance(owner, ast.Attribute):
                owner = owner.value
            if isinstance(owner, ast.Name) and owner.id in tagset_vars:
                names.extend(_strings(node.args[0], func, (), dyn))
    return names


def _astrodata_gemini_classes(cls):
    return [k for k in cls.__mro__ if k.__module__.startswith("astrodata_gemini")]


def _tag_methods(klass):
    """Return the ``@astro_data_tag`` function nodes of a class."""
    tree = ast.parse(textwrap.dedent(inspect.getsource(klass))).body[0]
    return [
        item
        for item in tree.body
        if isinstance(item, ast.FunctionDef)
        and any(
            getattr(dec, "id", "") == "astro_data_tag"
            for dec in item.decorator_list
        )
    ]


def tag_names(cls):
    """Return the sorted tag names a class (and its Gemini base) can define."""
    names = set()
    for klass in _astrodata_gemini_classes(cls):
        for method in _tag_methods(klass):
            names.update(_tags_of_method(method))
    return sorted(names)


def has_header_tags(cls):
    """Tell if the class itself defines tags named after header values.

    Only the tag methods defined in the class itself are examined, not the
    ones inherited from the Gemini level.
    """
    dyn = []
    for method in _tag_methods(cls):
        _tags_of_method(method, dyn)
    return bool(dyn)


# -- Descriptors ------------------------------------------------------------


def descriptors_of(cls):
    """Return ``[(name, defining_class)]`` for all the descriptors."""
    found = []
    for name in sorted(dir(cls)):
        if not getattr(getattr(cls, name, None), "descriptor_method", False):
            continue
        owner = next(k for k in cls.__mro__ if name in vars(k))
        found.append((name, owner))
    return found


def return_type(doc):
    """Return the type on the first line of the Returns section, or None."""
    match = re.search(r"^Returns\n-+\n(.+)", doc or "", re.M)
    if not match:
        return None
    text = match.group(1).strip()
    text = text.split(" : ")[0].strip().strip("<>:").strip()
    if not text or "`" in text:
        return None
    return text


# -- Writing the pages --------------------------------------------------------


def _title(text, char):
    return f"{text}\n{char * len(text)}\n"


def _first_line(obj):
    doc = inspect.getdoc(obj) or ""
    line = doc.strip().splitlines()[0] if doc.strip() else ""
    return re.sub(r"\|[^|]*\|", "", line).strip()


def _tags_section(cls):
    lines = [_title("Tags", "-")]
    names = tag_names(cls)
    lines.append(
        "These tags can be assigned to the data by this class, including "
        "those defined at the Gemini level.  Which ones apply depends on "
        "the data.\n"
    )
    lines.append(", ".join(f"``{n}``" for n in names) + "\n")
    if has_header_tags(cls):
        lines.append(
            "Additional tags named after header keyword values might also "
            "be present.\n"
        )
    return "\n".join(lines)


def _descriptors_section(cls, prefix):
    items = descriptors_of(cls)
    gemini = next(
        (k for k in cls.__mro__ if k.__name__ == "AstroDataGemini"), None
    )
    lines = [_title("Descriptors", "-")]
    lines.append(
        f"{len(items)} descriptors are defined"
        + (
            ", including those inherited from ``AstroDataGemini``.\n"
            if gemini is not None and cls is not gemini
            else ".\n"
        )
    )
    lines.append(".. list-table::")
    lines.append("   :header-rows: 1")
    lines.append("   :widths: 30 40 30\n")
    lines.append("   * - Descriptor")
    lines.append("     - Returns")
    lines.append("     - Defined in")
    for name, owner in items:
        label = f"{prefix}-descriptor-{name}"
        rtype = return_type(inspect.getdoc(getattr(cls, name)))
        lines.append(f"   * - :ref:`{name} <{label}>`")
        lines.append(f"     - {'``' + rtype + '``' if rtype else ''}")
        lines.append(f"     - ``{owner.__name__}``")
    lines.append("")
    for name, _ in items:
        lines.append(f".. _{prefix}-descriptor-{name}:\n")
        lines.append(f".. automethod:: {cls.__module__.rsplit('.', 1)[0]}"
                     f".{cls.__name__}.{name}")
        lines.append("   :no-index:\n")
    return "\n".join(lines)


def _page(title, cls, prefix, intro):
    path = f"{cls.__module__.rsplit('.', 1)[0]}.{cls.__name__}"
    return "\n".join(
        [
            f".. Generated by docs/_ext/gemini_pages.py.  Do not edit.\n",
            _title(title, "="),
            f"{intro}  The class is ``{path}``.\n",
            _tags_section(cls),
            _descriptors_section(cls, prefix),
        ]
    )


def _instrument_classes():
    """Return ``{package_name: class}`` for every instrument package."""
    import astrodata_gemini

    classes = {}
    for info in pkgutil.iter_modules(astrodata_gemini.__path__):
        if not info.ispkg:
            continue
        module = importlib.import_module(f"astrodata_gemini.{info.name}")
        for name in getattr(module, "__all__", []):
            if name.startswith("AstroData"):
                classes[info.name] = getattr(module, name)
    return classes


def _instrument_title(package, cls):
    """Return the instrument name from the docstring of its package."""
    module = importlib.import_module(cls.__module__.rsplit(".", 1)[0])
    match = re.search(r"AstroData class for (.+?) data", module.__doc__ or "")
    return match.group(1) if match else cls.__name__


def _write(path, text):
    """Write a file only if it changed, so unchanged pages are not rebuilt."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def _core_page():
    from astrodata import AstroData

    methods, properties = [], []
    for name, value in sorted(vars(AstroData).items()):
        if name.startswith("_"):
            continue
        if isinstance(value, property):
            properties.append((name, value))
        elif callable(value) and not getattr(value, "descriptor_method", False):
            methods.append((name, value))

    def table(items, role):
        rows = [".. list-table::", "   :widths: 30 70\n"]
        for name, obj in items:
            ref = f":external+astrodata:py:{role}:`astrodata.AstroData.{name}`"
            rows.append(f"   * - {ref}")
            rows.append(f"     - {_first_line(obj)}")
        return "\n".join(rows) + "\n"

    return "\n".join(
        [
            ".. Generated by docs/_ext/gemini_pages.py.  Do not edit.\n",
            _title("AstroData core methods", "*"),
            "These are the methods and properties of the core ``AstroData`` "
            "class, available on every object opened with ``astrodata``, "
            "whatever the instrument.  The links lead to the full "
            "documentation in the |astrodata| documentation.\n",
            _title("Methods", "="),
            table(methods, "meth"),
            _title("Properties", "="),
            table(properties, "attr"),
        ]
    )


def generate_pages(app):
    """Write all the generated pages (called when the builder starts)."""
    out = Path(app.srcdir) / "api"
    classes = _instrument_classes()
    gemini = classes.pop("gemini")

    _write(out / "core_methods.rst", _core_page())
    _write(
        out / "gemini_descriptors.rst",
        _page(
            "Gemini descriptors",
            gemini,
            "gemini",
            "The tags and descriptors defined at the Gemini level, the "
            "parent of all the instrument classes.",
        ),
    )

    entries = []
    for package, cls in sorted(classes.items()):
        title = _instrument_title(package, cls)
        _write(
            out / "instruments" / f"{package}.rst",
            _page(
                title,
                cls,
                package,
                f"The tags and descriptors for {title} data.",
            ),
        )
        entries.append((title, package))

    index = [
        ".. Generated by docs/_ext/gemini_pages.py.  Do not edit.\n",
        _title("Instruments", "*"),
        ".. toctree::",
        "   :maxdepth: 1\n",
    ]
    for title, package in sorted(entries, key=lambda e: e[0].lower()):
        index.append(f"   {title} <{package}>")
    _write(out / "instruments" / "index.rst", "\n".join(index) + "\n")
    logger.info("gemini_pages: wrote %d instrument pages", len(entries))


def setup(app):
    app.connect("builder-inited", generate_pages)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
